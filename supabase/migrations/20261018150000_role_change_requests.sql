create table if not exists public.vera_role_requests (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.vera_users(id),
  requested_role text not null check (requested_role in ('DIRECTOR', 'GERENTE', 'AUDITOR', 'JEFATURA')),
  reason text not null check (char_length(reason) between 10 and 500),
  status text not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by bigint references public.vera_users(id)
);

create unique index if not exists vera_role_requests_one_pending_per_user
  on public.vera_role_requests (user_id) where status = 'PENDING';
create index if not exists vera_role_requests_status_created
  on public.vera_role_requests (status, created_at desc);

alter table public.vera_role_requests enable row level security;
revoke all on public.vera_role_requests from public, anon, authenticated;
grant select, insert, update on public.vera_role_requests to service_role;
grant usage on sequence public.vera_role_requests_id_seq to service_role;

-- Resolve the request and change the role in one transaction. The API passes
-- the already authenticated VERA actor; the database checks SUPER_ADMIN again.
create or replace function public.review_vera_role_request(
  p_request_id bigint, p_reviewer_id bigint, p_approve boolean
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_request public.vera_role_requests%rowtype;
  v_reviewer public.vera_users%rowtype;
  v_user public.vera_users%rowtype;
begin
  select * into v_reviewer from public.vera_users where id = p_reviewer_id for update;
  if not found or v_reviewer.role <> 'SUPER_ADMIN' or v_reviewer.status <> 'ACTIVE' then
    raise exception 'Reviewer is not an active SUPER_ADMIN';
  end if;
  select * into v_request from public.vera_role_requests where id = p_request_id for update;
  if not found or v_request.status <> 'PENDING' then
    raise exception 'Role request is not pending';
  end if;
  select * into v_user from public.vera_users where id = v_request.user_id for update;
  if not found or v_user.status <> 'ACTIVE' or v_user.role = 'SUPER_ADMIN' then
    raise exception 'Target account cannot be changed';
  end if;
  if p_approve then
    update public.vera_users set role = v_request.requested_role,
      version = version + 1, updated_at = now() where id = v_user.id;
  end if;
  update public.vera_role_requests set
    status = case when p_approve then 'APPROVED' else 'REJECTED' end,
    reviewed_by = p_reviewer_id, reviewed_at = now()
  where id = p_request_id;
  return jsonb_build_object('requestId', p_request_id, 'userId', v_user.id,
    'role', case when p_approve then v_request.requested_role else v_user.role end,
    'status', case when p_approve then 'APPROVED' else 'REJECTED' end);
end;
$$;
revoke all on function public.review_vera_role_request(bigint,bigint,boolean) from public, anon, authenticated;
grant execute on function public.review_vera_role_request(bigint,bigint,boolean) to service_role;
