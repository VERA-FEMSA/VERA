-- Server-side accounts. No demo credentials are inserted into the remote database.
create table if not exists public.vera_users (
  -- Keep generated IDs outside the 1-6 range reserved by the local demo.
  id bigint generated by default as identity (start with 1000) primary key,
  username text not null unique,
  email text not null unique,
  name text not null,
  password_hash text not null,
  role text not null check (role in ('SUPER_ADMIN', 'DIRECTOR', 'GERENTE', 'JEFATURA', 'AUDITOR')),
  status text not null check (status in ('PENDING', 'ACTIVE', 'DISABLED')),
  requested_at timestamptz,
  two_factor_enabled boolean not null default false,
  two_factor_secret text,
  pending_secret text,
  version bigint not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vera_users_email_normalized check (email = lower(btrim(email))),
  constraint vera_users_username_normalized check (username = lower(btrim(username)))
);

create index if not exists vera_users_status_idx on public.vera_users (status);
alter table public.vera_users enable row level security;
revoke all on public.vera_users from public, anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on public.vera_users to service_role;
grant usage on sequence public.vera_users_id_seq to service_role;
